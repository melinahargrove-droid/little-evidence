function progressionMaxLevel(d){return d.maxLevel||Math.max(...d.anchors.map(a=>a.n))+1;}
function progressionSuggestedLevel(d,answers){
  const base=Number(answers.anchor)||0;
  const next=d.anchors.find(a=>a.n>base);
  const delta=answers.detail==='support'?-1:answers.detail==='independent'&&next?1:0;
  return Math.max(0,Math.min(progressionMaxLevel(d),base+delta));
}
function progressionDescription(d,n){
  if(n===0)return 'Not yet · the first described skill is not yet demonstrated';
  const exact=d.anchors.find(a=>a.n===n);
  if(exact)return 'Level '+n+' · '+exact.text;
  const lower=[...d.anchors].reverse().find(a=>a.n<n),upper=d.anchors.find(a=>a.n>n);
  if(upper)return 'Level '+n+' · '+(lower?'Builds on Level '+lower.n+' and shows parts of Level '+upper.n:'Shows emerging parts of Level '+upper.n)+': '+upper.text;
  return 'Level '+n+' · Beyond the final described anchor. Confirm this point in the official GOLD continuum using broader evidence.';
}
function progressionFamilyNext(d,n){
  const next=d.anchors.find(a=>a.n>n);
  if(next?.family)return 'Next goal: your child '+next.family+'. '+d.next;
  return 'Keep exploring this skill together in different books, activities, and everyday routines. '+d.next;
}
function progressionFamilyCopy(d,n){
  const lower=[...d.anchors].reverse().find(a=>a.n<=n);
  const strength=lower?.family?'Your child '+lower.family+'.':'Your child is beginning to explore '+d.family.toLowerCase()+'.';
  const emerging=n%2===1&&d.anchors.some(a=>a.n>n)?' Parts of the next skill are emerging.':'';
  return strength+emerging+' '+progressionFamilyNext(d,n);
}
